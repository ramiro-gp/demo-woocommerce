[CmdletBinding()]
param(
  [Parameter(Position = 0, Mandatory = $true)]
  [ValidateSet('start', 'status', 'stop', 'verify')][string]$Action
)

# start publishes this isolated test WordPress to the public Internet. Obtain
# the user's separate authorization before invoking it. Preparing these files,
# status, and stop do not authorize publication. No confirmation switch is used.
# Quick Tunnel URLs are temporary: stopping/restarting requires updating any
# configured callback URL and repeating the gateway checks.

$ErrorActionPreference = 'Stop'
if (Test-Path variable:PSNativeCommandUseErrorActionPreference) { $PSNativeCommandUseErrorActionPreference = $false }
$repoRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot)).TrimEnd('\')
if ($repoRoot -ine 'C:\Codigo\demo-woocommerce') { throw 'Use only the canonical C:\Codigo\demo-woocommerce repository.' }
$instance = 'h2-public'
$projectName = 'demo-woocommerce-h2-public'
$instanceRoot = Join-Path $repoRoot '.local/h2-public'
$httpsRoot = Join-Path $instanceRoot 'https'
$envFile = Join-Path $instanceRoot '.env'
$publicEnvFile = Join-Path $httpsRoot 'public.env'
$stateFile = Join-Path $httpsRoot 'state.json'
$composeFile = Join-Path $repoRoot 'compose.yaml'
$overlayFile = Join-Path $repoRoot 'compose.h2-https.yaml'
$cloudflaredPath = 'C:\Program Files (x86)\cloudflared\cloudflared.exe'
$localUrl = 'http://127.0.0.1:18081'
$utf8 = New-Object Text.UTF8Encoding($false)

function Assert-PrivatePaths {
  foreach ($path in @((Split-Path -Parent $repoRoot), $repoRoot, $PSScriptRoot, (Join-Path $repoRoot '.local'), $instanceRoot, $httpsRoot, $envFile, $publicEnvFile, $stateFile)) {
    if (Test-Path -LiteralPath $path) {
      if ((Get-Item -Force -LiteralPath $path).Attributes -band [IO.FileAttributes]::ReparsePoint) {
        throw 'A repository/private runtime path is a reparse point; inspect it before using the HTTPS helper.'
      }
    }
  }
}

function Assert-Instance {
  Assert-PrivatePaths
  if (-not (Test-Path -LiteralPath $envFile -PathType Leaf)) { throw 'Initialize and install H2 in the dedicated h2-public instance first.' }
  $values = @{}
  foreach ($line in [IO.File]::ReadAllLines($envFile)) {
    if ($line -match '^([A-Z_]+)=([a-zA-Z0-9@._-]+)$') { $values[$Matches[1]] = $Matches[2] }
    elseif ($line.Trim() -and -not $line.StartsWith('#')) { throw 'Invalid private instance configuration; restore the format generated by dev.ps1 init.' }
  }
  if ($values.LOCAL_INSTANCE -cne $instance -or $values.LOCAL_WP_PORT -ne '18081' -or $values.LOCAL_MAILPIT_PORT -ne '18026') {
    throw 'This helper requires h2-public with WordPress port 18081 and Mailpit port 18026.'
  }
  foreach ($key in $values.Keys) {
    $inheritedValue = [Environment]::GetEnvironmentVariable($key, 'Process')
    if ($inheritedValue -and $inheritedValue -cne $values[$key]) { throw "Inherited $key would override the fixed private instance; use a clean shell." }
  }
  if ([Environment]::GetEnvironmentVariable('H2_PUBLIC_SITE_URL', 'Process')) {
    throw 'Inherited H2_PUBLIC_SITE_URL would override the generated Quick Tunnel URL; use a clean shell.'
  }
  if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { throw 'Docker Desktop with Compose is required.' }
  if (-not (Test-Path -LiteralPath $composeFile -PathType Leaf)) { throw 'Base Compose file is missing.' }
}

function Invoke-Compose {
  param([string[]]$Arguments, [switch]$Public, [switch]$Capture)
  $dockerArgs = @('compose', '--project-directory', $repoRoot, '--project-name', $projectName, '--env-file', $envFile)
  if ($Public) { $dockerArgs += @('--env-file', $publicEnvFile) }
  $dockerArgs += @('-f', $composeFile)
  if ($Public) { $dockerArgs += @('-f', $overlayFile) }
  $dockerArgs += $Arguments
  if ($Capture) {
    # Windows PowerShell 5.1 wraps native stderr in NativeCommandError records,
    # including successful Docker progress. Judge the saved native exit code.
    $previousErrorPreference = $ErrorActionPreference
    try {
      $ErrorActionPreference = 'Continue'
      $result = & docker @dockerArgs 2>&1
      $nativeExitCode = $LASTEXITCODE
    } finally { $ErrorActionPreference = $previousErrorPreference }
    if ($nativeExitCode -ne 0) { throw "Docker Compose failed with exit code $nativeExitCode." }
    return ($result | ForEach-Object { "$_" })
  }
  & docker @dockerArgs
  if ($LASTEXITCODE -ne 0) { throw "Docker Compose failed with exit code $LASTEXITCODE." }
}

function Read-State {
  if (-not (Test-Path -LiteralPath $stateFile -PathType Leaf)) { return $null }
  try { $state = [IO.File]::ReadAllText($stateFile) | ConvertFrom-Json }
  catch { throw 'Private HTTPS state is unreadable; inspect it before starting or stopping a tunnel.' }
  if ($state.formatVersion -ne 1 -or $state.instance -cne $instance -or $state.runId -notmatch '^[0-9]{8}T[0-9]{6}Z-[a-f0-9]{12}$') {
    throw 'Private HTTPS state does not identify a supported h2-public run.'
  }
  return $state
}

function Save-State {
  param([object]$State)
  $json = ($State | ConvertTo-Json -Depth 5) + "`n"
  [IO.File]::WriteAllText((Join-Path $httpsRoot ($State.runId + '.state.json')), $json, $utf8)
  [IO.File]::WriteAllText($stateFile, $json, $utf8)
}

function Get-OwnedProcess {
  param([object]$State)
  if (-not $State -or -not $State.processId) { return $null }
  $process = Get-Process -Id ([int]$State.processId) -ErrorAction SilentlyContinue
  if (-not $process) { return $null }
  try {
    $actualPath = $process.Path
    $actualStarted = $process.StartTime.ToUniversalTime()
    # PowerShell 7 converts ISO JSON timestamps to DateTime automatically;
    # parsing that object as a string would lose ticks and reinterpret its zone.
    # PowerShell 5.1 leaves the value as the original ISO string.
    $expectedStarted = if ($State.processStartedAtUtc -is [DateTime]) {
      $State.processStartedAtUtc.ToUniversalTime()
    } else {
      [DateTime]::Parse($State.processStartedAtUtc, [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]::RoundtripKind).ToUniversalTime()
    }
  } catch { throw 'Cannot validate the recorded process identity; no process was stopped.' }
  if ($State.executable -ine $cloudflaredPath -or $actualPath -ine $cloudflaredPath -or $actualStarted.Ticks -ne $expectedStarted.Ticks) {
    throw 'Recorded PID belongs to a different process; no process was stopped. Inspect the private state.'
  }
  return $process
}

function Stop-OwnedProcess {
  param([object]$State)
  $process = Get-OwnedProcess $State
  if ($process) {
    # Stop only this validated PID; never kill cloudflared by name or stop a service.
    $process.Kill()
    if (-not $process.WaitForExit(10000)) { throw 'The validated tunnel process did not exit within 10 seconds.' }
  }
}

function Assert-NoOriginTunnel {
  # Inspect without printing command lines or terminating any unrecorded PID.
  $otherTunnels = @(Get-CimInstance Win32_Process -Filter "Name = 'cloudflared.exe'" | Where-Object {
    $_.CommandLine -match '--url(?:=|\s+)["'']?http://(?:127\.0\.0\.1|localhost):18081(?:["''\s/]|$)'
  })
  if ($otherTunnels.Count) { throw 'A cloudflared process still targets port 18081; it was not stopped.' }
}

function Assert-NoInheritedTunnelConfig {
  $directories = @(
    (Join-Path $env:USERPROFILE '.cloudflared'),
    (Join-Path $env:USERPROFILE '.cloudflare-warp'),
    (Join-Path $env:USERPROFILE 'cloudflare-warp'),
    (Join-Path $repoRoot '.cloudflared')
  )
  foreach ($directory in $directories) {
    foreach ($name in @('config.yml', 'config.yaml')) {
      if (Test-Path -LiteralPath (Join-Path $directory $name) -PathType Leaf) {
        throw 'An existing cloudflared config file could affect this Quick Tunnel. It was not modified; use an environment without inherited configuration.'
      }
    }
  }
  # Reject inherited credentials/options rather than print or override their values.
  $inherited = @(Get-ChildItem Env: | Where-Object { $_.Value -and ($_.Name -match '^(TUNNEL_|CLOUDFLARED_)' -or $_.Name -in @('NO_TLS_VERIFY', 'NO_AUTOUPDATE')) })
  if ($inherited.Count) { throw 'Inherited cloudflared environment options were found. Use a clean shell; their values were not displayed or changed.' }
  Assert-NoOriginTunnel
}

function Assert-PublicUrl {
  param([string]$Url)
  if ($Url -cnotmatch '^https://[a-z0-9]+(?:-[a-z0-9]+)*\.trycloudflare\.com$') { throw 'The tunnel did not provide a supported HTTPS trycloudflare.com origin.' }
}

function Read-LiveLog {
  param([string]$Path)
  # Start-Process keeps redirected logs open on Windows. Share its writer while
  # reading the current contents; a plain ReadAllText opens with incompatible sharing.
  $stream = [IO.File]::Open($Path, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::ReadWrite)
  try {
    $reader = New-Object IO.StreamReader($stream)
    try { return $reader.ReadToEnd() } finally { $reader.Dispose() }
  } finally { $stream.Dispose() }
}

function Read-PublicResponse {
  param([string]$Url, [string]$Origin)
  $current = [Uri]$Url
  for ($redirect = 0; $redirect -le 5; $redirect++) {
    if ($current.Scheme -cne 'https' -or $current.GetLeftPart([UriPartial]::Authority) -cne $Origin -or $current.UserInfo) {
      throw 'Public HTTP verification refused an insecure or different-origin redirect.'
    }
    $request = [Net.HttpWebRequest]::Create($current)
    $request.Method = 'GET'
    $request.Accept = '*/*'
    $request.UserAgent = 'demo-woocommerce-H2-HTTPS-check'
    $request.AllowAutoRedirect = $false
    $request.Timeout = 15000
    $request.ReadWriteTimeout = 15000
    $response = $null
    try { $response = $request.GetResponse() }
    catch [Net.WebException] {
      $response = $_.Exception.Response
      if (-not $response) { throw 'Public HTTPS transport or certificate verification failed.' }
    }
    try {
      $status = [int]$response.StatusCode
      if ($status -in @(301, 302, 303, 307, 308)) {
        $location = [string]$response.Headers['Location']
        if (-not $location) { throw 'Public HTTP response has an empty redirect target.' }
        $current = New-Object Uri($current, $location)
        continue
      }
      if ($status -ne 200) { throw "Public HTTPS verification returned HTTP $status." }
      $reader = New-Object IO.StreamReader($response.GetResponseStream())
      try { $body = $reader.ReadToEnd() } finally { $reader.Dispose() }
      # Never return response headers: login/cart endpoints can set sensitive cookies.
      return [pscustomobject]@{ Body = $body; Redirects = $redirect }
    } finally { $response.Dispose() }
  }
  throw 'Public HTTPS verification exceeded five redirects.'
}

function Test-PublicSite {
  param([string]$Origin)
  Assert-PublicUrl $Origin
  $oldProtocols = [Net.ServicePointManager]::SecurityProtocol
  [Net.ServicePointManager]::SecurityProtocol = $oldProtocols -bor [Net.SecurityProtocolType]::Tls12
  try {
    $homeResponse = Read-PublicResponse -Url ($Origin + '/') -Origin $Origin
    $login = Read-PublicResponse -Url ($Origin + '/wp-login.php') -Origin $Origin
    $apiResponse = Read-PublicResponse -Url ($Origin + '/index.php?rest_route=/wc/store/v1') -Origin $Origin
    try { $api = $apiResponse.Body | ConvertFrom-Json }
    catch { throw 'The public Store API namespace did not return JSON.' }
    if ($api.namespace -cne 'wc/store/v1' -or -not $api.routes) { throw 'The public WooCommerce Store API namespace is unavailable.' }
    $links = @($api._links.up)
    foreach ($route in $api.routes.PSObject.Properties) { $links += @($route.Value._links.self) }
    $checkedLinks = 0
    foreach ($link in $links) {
      if (-not $link.href) { continue }
      $uri = [Uri]$link.href
      if (-not $uri.IsAbsoluteUri -or $uri.Scheme -cne 'https' -or $uri.GetLeftPart([UriPartial]::Authority) -cne $Origin -or $uri.UserInfo) {
        throw 'WordPress generated an insecure or different-origin Store API base/link.'
      }
      $checkedLinks++
    }
    if ($checkedLinks -eq 0) { throw 'The Store API response did not include a verifiable public HTTPS base/link.' }
    Write-Host "PASS: public HTTPS home and wp-login HTTP 200; same-origin redirects; Store API rest_route and $checkedLinks HTTPS links."
  } finally { [Net.ServicePointManager]::SecurityProtocol = $oldProtocols }
}

function Start-Https {
  if (-not (Test-Path -LiteralPath $cloudflaredPath -PathType Leaf)) { throw 'The expected cloudflared executable is not installed.' }
  if (-not (Test-Path -LiteralPath $overlayFile -PathType Leaf)) { throw 'The H2 HTTPS Compose overlay is missing.' }
  $previousState = Read-State
  if (Get-OwnedProcess $previousState) { throw 'The recorded h2-public tunnel is already running. Use status or verify.' }
  Assert-NoInheritedTunnelConfig
  # Do not publish an uninitialized site. This only reads installation/plugin state.
  $null = Invoke-Compose -Arguments @('run', '--rm', '-T', '--no-deps', 'wpcli', 'core', 'is-installed') -Capture
  foreach ($slug in @('woocommerce', 'woocommerce-mercadopago')) {
    $null = Invoke-Compose -Arguments @('run', '--rm', '-T', '--no-deps', 'wpcli', 'plugin', 'is-active', $slug) -Capture
  }
  $null = New-Item -ItemType Directory -Force -Path $httpsRoot
  $runId = [DateTime]::UtcNow.ToString('yyyyMMddTHHmmssZ') + '-' + [Guid]::NewGuid().ToString('N').Substring(0, 12)
  $stdout = Join-Path $httpsRoot ($runId + '.stdout.log')
  $stderr = Join-Path $httpsRoot ($runId + '.stderr.log')
  $state = [pscustomobject][ordered]@{
    formatVersion = 1; instance = $instance; runId = $runId; status = 'starting'
    processId = 0; processStartedAtUtc = $null; executable = $cloudflaredPath
    publicUrl = $null; createdAtUtc = [DateTime]::UtcNow.ToString('o')
    stdout = [IO.Path]::GetFileName($stdout); stderr = [IO.Path]::GetFileName($stderr)
    stoppedAtUtc = $null; failure = $null
  }
  Save-State $state
  $wordpressStopped = $false
  try {
    # Stop the dedicated origin before obtaining its public URL to avoid serving
    # the old localhost configuration during the startup window.
    $wordpressStopped = $true
    Invoke-Compose -Arguments @('stop', 'wordpress')
    $process = Start-Process -FilePath $cloudflaredPath -ArgumentList @(
      'tunnel', '--no-autoupdate', '--url', $localUrl,
      '--metrics', '127.0.0.1:18181', '--loglevel', 'info'
    ) -WorkingDirectory $repoRoot -WindowStyle Hidden -PassThru -RedirectStandardOutput $stdout -RedirectStandardError $stderr
    $state.processId = $process.Id
    $state.processStartedAtUtc = $process.StartTime.ToUniversalTime().ToString('o')
    Save-State $state
    $deadline = [DateTime]::UtcNow.AddSeconds(60)
    do {
      $process.Refresh()
      if ($process.HasExited) { throw 'cloudflared exited before the Quick Tunnel became ready. Inspect its private run logs.' }
      $logText = ''
      foreach ($log in @($stdout, $stderr)) {
        if (Test-Path -LiteralPath $log -PathType Leaf) { $logText += Read-LiveLog $log }
      }
      $match = [regex]::Match($logText, 'https://[a-z0-9]+(?:-[a-z0-9]+)*\.trycloudflare\.com\b')
      if ($match.Success) { $state.publicUrl = $match.Value; break }
      Start-Sleep -Milliseconds 250
    } while ([DateTime]::UtcNow -lt $deadline)
    if (-not $state.publicUrl) { throw 'No Quick Tunnel URL was received within 60 seconds. Inspect the private run logs.' }
    Assert-PublicUrl $state.publicUrl
    Save-State $state
    [IO.File]::WriteAllText($publicEnvFile, "H2_PUBLIC_SITE_URL=$($state.publicUrl)`n", $utf8)
    Invoke-Compose -Public -Arguments @('config', '--quiet')
    Invoke-Compose -Public -Arguments @('up', '-d', '--wait', '--wait-timeout', '180', 'wordpress')
    # Give the edge connector a short readiness window after the origin is ready.
    $verifyDeadline = [DateTime]::UtcNow.AddSeconds(60)
    do {
      try { Test-PublicSite -Origin $state.publicUrl; break }
      catch {
        if ([DateTime]::UtcNow -ge $verifyDeadline) { throw }
        if (-not (Get-OwnedProcess $state)) { throw 'The owned tunnel exited during HTTPS readiness verification.' }
        Start-Sleep -Seconds 1
      }
    } while ($true)
    $state.status = 'running'
    Save-State $state
    Write-Host "Public test site: $($state.publicUrl) | Owned cloudflared PID: $($state.processId)"
    Write-Host 'Keep this computer and Docker running. Stop with scripts/h2-https.ps1 stop when finished.'
  } catch {
    $state.status = 'failed'
    $state.failure = $_.Exception.Message
    $cleanupErrors = New-Object 'System.Collections.Generic.List[string]'
    $originStopped = $false
    if ($wordpressStopped) {
      # Close the origin first, including after public verification/up failed.
      # Never serve the localhost configuration through a possibly live tunnel.
      try { Invoke-Compose -Arguments @('stop', 'wordpress'); $originStopped = $true }
      catch { $cleanupErrors.Add('Could not confirm that dedicated WordPress stopped; inspect Docker immediately.') }
    }
    $tunnelStopped = $false
    try { Stop-OwnedProcess $state; Assert-NoOriginTunnel; $tunnelStopped = $true }
    catch { $cleanupErrors.Add($_.Exception.Message) }
    if ($tunnelStopped -and $wordpressStopped) {
      try { Invoke-Compose -Arguments @('up', '-d', '--wait', '--wait-timeout', '180', 'wordpress') }
      catch { $cleanupErrors.Add('Base WordPress restoration failed; inspect Docker before retrying.') }
    }
    if ($tunnelStopped) { $state.stoppedAtUtc = [DateTime]::UtcNow.ToString('o') }
    else {
      $state.status = 'cleanup-blocked'
      $state.stoppedAtUtc = $null
      if ($originStopped) { $cleanupErrors.Add('Tunnel shutdown is unconfirmed. Dedicated WordPress is stopped; base restoration was not attempted.') }
      else { $cleanupErrors.Add('Tunnel shutdown and origin stop are unconfirmed. Base restoration was not attempted; inspect the recorded PID and Docker immediately.') }
    }
    if ($cleanupErrors.Count) { $state.failure += ' Cleanup: ' + ($cleanupErrors -join ' ') }
    Save-State $state
    throw "HTTPS start failed: $($state.failure) Private diagnostics: .local/h2-public/https/$runId.*"
  }
}

function Show-Status {
  $state = Read-State
  if ($state) {
    $process = Get-OwnedProcess $state
    Write-Host "Recorded run: $($state.status) | Owned tunnel active: $([bool]$process) | PID: $($state.processId)"
    if ($state.publicUrl) { Assert-PublicUrl $state.publicUrl; Write-Host "Recorded public URL: $($state.publicUrl)" }
  } else { Write-Host 'No HTTPS run has been recorded for h2-public.' }
  Invoke-Compose -Arguments @('ps')
}

function Stop-Https {
  # Shut the origin first so an unreadable state, identity mismatch, or process
  # shutdown failure cannot leave a local site offered through a live tunnel.
  Invoke-Compose -Arguments @('stop', 'wordpress')
  $state = Read-State
  try { Stop-OwnedProcess $state; Assert-NoOriginTunnel }
  catch {
    if ($state) {
      $state.status = 'cleanup-blocked'
      $state.failure = $_.Exception.Message + ' Dedicated WordPress is stopped; base restoration was not attempted.'
      $state.stoppedAtUtc = $null
      Save-State $state
    }
    throw 'Tunnel shutdown could not be confirmed. Dedicated WordPress is stopped; inspect the recorded process. Base restoration was not attempted.'
  }
  # Base Compose contains the local URL; no database/volume/password is replaced.
  Invoke-Compose -Arguments @('up', '-d', '--wait', '--wait-timeout', '180', 'wordpress')
  if ($state) {
    $state.status = 'stopped'
    $state.stoppedAtUtc = [DateTime]::UtcNow.ToString('o')
    Save-State $state
  }
  Write-Host 'Owned tunnel stopped. h2-public restored to http://localhost:18081; private logs and volumes preserved.'
}

Assert-Instance
$mutex = New-Object Threading.Mutex($false, 'Local\demo-woocommerce-h2-public-https')
$locked = $false
try {
  try { $locked = $mutex.WaitOne(0) } catch [Threading.AbandonedMutexException] { $locked = $true }
  if (-not $locked) { throw 'Another h2-public HTTPS helper is running; wait for it to finish.' }
  switch ($Action) {
    'start' { Start-Https }
    'status' { Show-Status }
    'stop' { Stop-Https }
    'verify' {
      $state = Read-State
      if (-not (Get-OwnedProcess $state) -or $state.status -ne 'running') { throw 'A recorded running h2-public tunnel is required for read-only verification.' }
      Test-PublicSite -Origin $state.publicUrl
    }
  }
} finally {
  if ($locked) { $mutex.ReleaseMutex() }
  $mutex.Dispose()
}
