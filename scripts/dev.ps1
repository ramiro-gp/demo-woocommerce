[CmdletBinding()]
param(
  [Parameter(Position = 0, Mandatory = $true)]
  [ValidateSet('init', 'start', 'stop', 'status', 'logs', 'wp', 'backup', 'restore', 'reset-db', 'reset-all', 'doctor', 'mail-test')]
  [string]$Action,
  [ValidatePattern('^[a-z][a-z0-9-]{0,29}$')][string]$Instance = 'local',
  [ValidateRange(1024, 65535)][int]$WordPressPort = 8080,
  [ValidateRange(1024, 65535)][int]$MailpitPort = 8025,
  [ValidateSet('wordpress', 'db', 'mailpit')][string]$Service = 'wordpress',
  [ValidatePattern('^[a-zA-Z0-9][a-zA-Z0-9_-]{0,79}$')][string]$BackupId,
  [string]$ConfirmName,
  [string[]]$WpArgs = @()
)

$ErrorActionPreference = 'Stop'
if (Test-Path variable:PSNativeCommandUseErrorActionPreference) { $PSNativeCommandUseErrorActionPreference = $false }
$repoRoot = Split-Path -Parent $PSScriptRoot
$projectName = "demo-woocommerce-$Instance"
$instanceRoot = Join-Path $repoRoot ".local/$Instance"
$envFile = Join-Path $instanceRoot '.env'
$backupRoot = Join-Path $instanceRoot 'backups'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Invoke-Docker {
  param([string[]]$DockerArgs, [switch]$Capture)
  if ($Capture) {
    $result = & docker @DockerArgs 2>&1
    if ($LASTEXITCODE -ne 0) { throw "Docker failed ($LASTEXITCODE): $($result -join [Environment]::NewLine)" }
    return ($result | ForEach-Object { "$_" })
  }
  & docker @DockerArgs
  if ($LASTEXITCODE -ne 0) { throw "Docker failed with exit code $LASTEXITCODE." }
}

function Invoke-Compose {
  param([string[]]$ComposeArgs, [switch]$Capture)
  $dockerArgs = @('compose', '--project-directory', $repoRoot, '--project-name', $projectName, '--env-file', $envFile, '-f', (Join-Path $repoRoot 'compose.yaml')) + $ComposeArgs
  Invoke-Docker -DockerArgs $dockerArgs -Capture:$Capture
}

function Invoke-Wp {
  param([string[]]$Arguments, [switch]$Capture)
  Invoke-Compose -ComposeArgs (@('run', '--rm', '-T', '--no-deps', 'wpcli') + $Arguments) -Capture:$Capture
}

function Invoke-Tool {
  param([string]$Tool, [string[]]$Arguments = @(), [switch]$Capture)
  Invoke-Compose -ComposeArgs (@('run', '--rm', '-T', '--no-deps', '--entrypoint', 'sh', 'wpcli', "/opt/local-tools/$Tool") + $Arguments) -Capture:$Capture
}

function Assert-Engine {
  if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { throw 'Install Docker Desktop with Compose and enable Linux containers first.' }
  $kind = (Invoke-Docker -DockerArgs @('info', '--format', '{{.OSType}}') -Capture) -join ''
  if ($kind.Trim() -ne 'linux') { throw 'Docker Desktop must be running with Linux containers.' }
  $null = Invoke-Docker -DockerArgs @('compose', 'version', '--short') -Capture
}

function Read-LocalConfig {
  if (-not (Test-Path -LiteralPath $envFile -PathType Leaf)) { throw "Run init for instance '$Instance' first." }
  $values = @{}
  foreach ($line in [IO.File]::ReadAllLines($envFile)) {
    if ($line -match '^([A-Z_]+)=([a-zA-Z0-9@._-]+)$') { $values[$Matches[1]] = $Matches[2] }
    elseif ($line.Trim() -ne '' -and -not $line.StartsWith('#')) { throw 'Invalid local .env syntax. Use the format generated by init.' }
  }
  if ($values.LOCAL_INSTANCE -ne $Instance) { throw 'Instance name differs from the local configuration.' }
  foreach ($key in @('LOCAL_WP_PORT', 'LOCAL_MAILPIT_PORT')) {
    $port = 0
    if (-not [int]::TryParse($values[$key], [ref]$port) -or $port -lt 1024 -or $port -gt 65535) { throw "Invalid $key." }
  }
  if ($values.LOCAL_WP_PORT -eq $values.LOCAL_MAILPIT_PORT) { throw 'WordPress and Mailpit must use different ports.' }
  if (-not $values.LOCAL_ADMIN_USER -or -not $values.LOCAL_ADMIN_EMAIL) { throw 'Administrator configuration is incomplete.' }
  foreach ($name in @('db-password.txt', 'db-root-password.txt', 'wp-admin-password.txt')) {
    $secret = Join-Path $instanceRoot "secrets/$name"
    if (-not (Test-Path -LiteralPath $secret -PathType Leaf) -or (Get-Item -LiteralPath $secret).Length -lt 32) { throw "Missing or incomplete secret: $name. Restore the original private configuration; init never rotates existing passwords." }
  }
  return $values
}

function New-RandomHex {
  param([int]$Bytes = 32)
  $buffer = New-Object byte[] $Bytes
  $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
  try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
  return ([BitConverter]::ToString($buffer)).Replace('-', '').ToLowerInvariant()
}

function Initialize-Local {
  Assert-Engine
  if (Test-Path -LiteralPath $envFile) {
    $null = Read-LocalConfig
    Write-Host "Instance '$Instance' already initialized; configuration and secrets preserved."
    return
  }
  if ($WordPressPort -eq $MailpitPort) { throw 'WordPress and Mailpit must use different ports.' }
  $existingVolumes = Invoke-Docker -DockerArgs @('volume', 'ls', '--filter', "label=com.docker.compose.project=$projectName", '--format', '{{.Name}}') -Capture
  if ($existingVolumes) { throw 'Existing project volumes found without configuration. Restore its original .local directory before continuing.' }
  if (Test-Path -LiteralPath (Join-Path $instanceRoot 'secrets')) { throw 'Partial private configuration exists. Recover or inspect it explicitly; secrets will not be overwritten.' }
  $null = New-Item -ItemType Directory -Force -Path (Join-Path $instanceRoot 'secrets'), $backupRoot
  foreach ($name in @('db-password.txt', 'db-root-password.txt', 'wp-admin-password.txt')) {
    [IO.File]::WriteAllText((Join-Path $instanceRoot "secrets/$name"), (New-RandomHex) + "`n", $utf8)
  }
  $admin = 'local_owner_' + (New-RandomHex -Bytes 4)
  $config = "LOCAL_INSTANCE=$Instance`nLOCAL_WP_PORT=$WordPressPort`nLOCAL_MAILPIT_PORT=$MailpitPort`nLOCAL_ADMIN_USER=$admin`nLOCAL_ADMIN_EMAIL=owner@example.test`n"
  [IO.File]::WriteAllText($envFile, $config, $utf8)
  $null = Read-LocalConfig
  Invoke-Compose -ComposeArgs @('config', '--quiet')
  Write-Host "Initialized $projectName. Admin user: $admin. Password: .local/$Instance/secrets/wp-admin-password.txt"
}

function Start-Local {
  Invoke-Compose -ComposeArgs @('up', '-d', '--wait', '--wait-timeout', '180', 'db', 'mailpit', 'wordpress')
  try { Invoke-Tool -Tool 'install.sh' }
  catch {
    Invoke-Compose -ComposeArgs @('stop', 'wordpress')
    throw
  }
  Write-Host "Site: http://localhost:$($localConfig.LOCAL_WP_PORT) | Admin: http://localhost:$($localConfig.LOCAL_WP_PORT)/wp-admin/ | Mailpit: http://localhost:$($localConfig.LOCAL_MAILPIT_PORT)"
}

function Test-WordPressRunning {
  $ids = Invoke-Compose -ComposeArgs @('ps', '--status', 'running', '-q', 'wordpress') -Capture
  return [bool]$ids
}

function Ensure-Database {
  Invoke-Compose -ComposeArgs @('up', '-d', '--wait', '--wait-timeout', '180', 'db', 'mailpit')
}

function New-Backup {
  param([string]$Id)
  if (-not $Id) { $Id = (Get-Date -Format 'yyyyMMdd-HHmmss') + '-' + (New-RandomHex -Bytes 3) }
  $target = Join-Path $backupRoot $Id
  if (Test-Path -LiteralPath $target) { throw "Backup '$Id' already exists; it will not be overwritten." }
  Ensure-Database | Out-Host
  $wasRunning = Test-WordPressRunning
  try {
    if ($wasRunning) { Invoke-Compose -ComposeArgs @('stop', 'wordpress') | Out-Host }
    $null = New-Item -ItemType Directory -Path $target
    Invoke-Tool -Tool 'backup.sh' -Arguments @($Id) | Out-Host
    $manifest = [ordered]@{
      formatVersion = 1
      backupId = $Id
      project = $projectName
      createdAtUtc = [DateTime]::UtcNow.ToString('o')
      dependencies = (Get-Content -Raw -LiteralPath (Join-Path $repoRoot 'config/dependencies.json') | ConvertFrom-Json)
      files = @(
        @{ name = 'database.sql'; sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $target 'database.sql')).Hash.ToLowerInvariant() },
        @{ name = 'wordpress.tar.gz'; sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $target 'wordpress.tar.gz')).Hash.ToLowerInvariant() }
      )
    }
    [IO.File]::WriteAllText((Join-Path $target 'manifest.json'), ($manifest | ConvertTo-Json -Depth 10) + "`n", $utf8)
    Write-Host "Backup complete: .local/$Instance/backups/$Id"
  }
  finally { if ($wasRunning) { Invoke-Compose -ComposeArgs @('start', 'wordpress') | Out-Host } }
  return $Id
}

function Assert-Confirmation {
  if ($ConfirmName -cne $projectName) { throw "This action replaces data. Repeat with -ConfirmName '$projectName' to identify the exact project." }
}

function Assert-Backup {
  param([string]$Id)
  if (-not $Id) { throw 'restore requires -BackupId.' }
  $target = Join-Path $backupRoot $Id
  $manifestPath = Join-Path $target 'manifest.json'
  if (-not (Test-Path -LiteralPath $manifestPath -PathType Leaf)) { throw 'Backup has no completed manifest; restore refused.' }
  $manifest = Get-Content -Raw -LiteralPath $manifestPath | ConvertFrom-Json
  if ($manifest.formatVersion -ne 1 -or $manifest.backupId -cne $Id -or $manifest.project -cne $projectName) { throw 'Backup format, ID or originating project does not match this instance.' }
  if ($manifest.dependencies.wordpress.digest -ne $dependencies.wordpress.digest -or $manifest.dependencies.mariadb.digest -ne $dependencies.mariadb.digest) { throw 'Backup versions differ. Plan a migration instead of restoring across versions implicitly.' }
  if (@($manifest.files).Count -ne 2) { throw 'Invalid backup file manifest.' }
  foreach ($name in @('database.sql', 'wordpress.tar.gz')) {
    $entry = @($manifest.files | Where-Object { $_.name -ceq $name })
    $file = Join-Path $target $name
    if ($entry.Count -ne 1 -or -not (Test-Path -LiteralPath $file -PathType Leaf)) { throw "Missing backup file: $name." }
    $hash = (Get-FileHash -Algorithm SHA256 -LiteralPath $file).Hash.ToLowerInvariant()
    if ($hash -cne $entry[0].sha256) { throw "Backup checksum mismatch: $name. No data was replaced." }
  }
}

function Assert-ProjectVolumes {
  foreach ($logicalName in @('db_data', 'wordpress_data', 'mailpit_data')) {
    $volumeName = "${projectName}_$logicalName"
    $info = (Invoke-Docker -DockerArgs @('volume', 'inspect', $volumeName) -Capture) -join "`n" | ConvertFrom-Json
    if ($info[0].Labels.'com.docker.compose.project' -cne $projectName -or $info[0].Labels.'com.docker.compose.volume' -cne $logicalName) {
      throw "Volume ownership check failed: $volumeName. No volumes were removed."
    }
  }
}

if ($Action -eq 'init') { Initialize-Local; return }
Assert-Engine
if ($Action -eq 'doctor' -and -not (Test-Path -LiteralPath $envFile)) {
  Invoke-Docker -DockerArgs @('version', '--format', 'Docker server: {{.Server.Version}} ({{.Server.Os}}/{{.Server.Arch}})')
  Invoke-Docker -DockerArgs @('compose', 'version')
  Write-Host 'Docker is ready. Run init, then start, for application checks.'
  return
}
$localConfig = Read-LocalConfig
$dependencies = Get-Content -Raw -LiteralPath (Join-Path $repoRoot 'config/dependencies.json') | ConvertFrom-Json
Invoke-Compose -ComposeArgs @('config', '--quiet')

switch ($Action) {
  'start' { Start-Local }
  'stop' { Invoke-Compose -ComposeArgs @('stop') }
  'status' { Invoke-Compose -ComposeArgs @('ps', '-a') }
  'logs' { Invoke-Compose -ComposeArgs @('logs', '--tail', '100', '--follow', $Service) }
  'wp' {
    if ($WpArgs.Count -eq 0) { throw "Provide -WpArgs @('core', 'version'), for example." }
    Invoke-Wp -Arguments $WpArgs
  }
  'mail-test' { Invoke-Wp -Arguments @('eval-file', '/opt/local-tools/mail-test.php') }
  'backup' { $null = New-Backup -Id $BackupId }
  'restore' {
    Assert-Confirmation
    Assert-Backup -Id $BackupId
    Ensure-Database
    Invoke-Tool -Tool 'validate-backup.sh' -Arguments @($BackupId)
    $safetyId = New-Backup
    Write-Host "Pre-restore backup: $safetyId"
    Invoke-Compose -ComposeArgs @('stop', 'wordpress')
    try {
      Invoke-Tool -Tool 'restore.sh' -Arguments @($BackupId)
      Start-Local
    }
    catch { throw "Restore failed; WordPress remains stopped. Recover using backup '$safetyId'. $($_.Exception.Message)" }
  }
  'reset-db' {
    Assert-Confirmation
    $safetyId = New-Backup
    Write-Host "Pre-reset backup: $safetyId"
    Invoke-Compose -ComposeArgs @('stop', 'wordpress')
    Invoke-Wp -Arguments @('db', 'reset', '--yes')
    Start-Local
  }
  'reset-all' {
    Assert-Confirmation
    Assert-ProjectVolumes
    $safetyId = New-Backup
    Write-Host "Pre-reset backup: $safetyId"
    Invoke-Compose -ComposeArgs @('down')
    Assert-ProjectVolumes
    foreach ($logicalName in @('db_data', 'wordpress_data', 'mailpit_data')) {
      Invoke-Docker -DockerArgs @('volume', 'rm', "${projectName}_$logicalName")
    }
    Start-Local
  }
  'doctor' {
    Invoke-Docker -DockerArgs @('version', '--format', 'Docker server: {{.Server.Version}} ({{.Server.Os}}/{{.Server.Arch}})')
    Invoke-Docker -DockerArgs @('compose', 'version')
    Invoke-Compose -ComposeArgs @('ps', '-a')
    Invoke-Wp -Arguments @('core', 'version', '--extra')
    Invoke-Wp -Arguments @('--version')
    Invoke-Compose -ComposeArgs @('exec', '-T', 'wordpress', 'php', '--version')
    Invoke-Compose -ComposeArgs @('exec', '-T', 'db', 'mariadb', '--version')
    Invoke-Compose -ComposeArgs @('exec', '-T', 'mailpit', '/mailpit', 'version')
  }
}
